/* Presentation layer over the existing session, terminal and editor controllers. */
(() => {
  'use strict';
  if (window.SerenaWorkspace) return;
  const $ = id => document.getElementById(id);
  const icon = name => `<i data-lucide="${name}" aria-hidden="true"></i>`;
  const icons = () => window.lucide?.createIcons();
  let refreshFrame = 0, changesCwd = '', changesGeneration = 0, changesVisible = false;
  const state = window.SerenaWorkspace = {
    singleSid: null,
    refresh() {
      if (refreshFrame) return;
      refreshFrame = requestAnimationFrame(() => { refreshFrame = 0; refresh(); });
    },
    closeProjects() {
      $('projectSidebar').classList.remove('workspace-open');
      $('workspaceProject').setAttribute('aria-expanded', 'false');
    },
    refreshProject() { state.refresh(); },
    terminalBody(mount, sid, agent) {
      const header = document.createElement('header');
      header.className = 'workspace-terminal-head';
      header.innerHTML = _agentBadge(agent) + '<span>' + esc(_agentLabel(agent)) + '</span>';
      const copy = document.createElement('button');
      copy.type = 'button'; copy.textContent = sid.slice(0, 8);
      copy.title = 'Copy session ID: ' + sid;
      copy.addEventListener('click', e => {
        e.stopPropagation();
        // Reconciled new-session mounts can acquire their durable ID later.
        _copyPlainText(mount.dataset.sid || sid).then(() => showToast('Session ID copied', {variant:'success'}))
          .catch(() => showToast('Clipboard unavailable', {variant:'error'}));
      });
      header.append(copy);
      const body = document.createElement('div'); body.className = 'workspace-terminal-body';
      mount.append(header, body); return body;
    },
  };

  const navIcons = {chats:'messages-square',fleet:'workflow',tasks:'square-check',memory:'brain',knowledge:'library',usage:'gauge',persona:'fingerprint',tooling:'wrench'};
  const nav = document.querySelector('.tab-bar');
  for (const name of Object.keys(navIcons)) {
    const tab = nav.querySelector(`[data-tab="${name}"]`);
    tab.insertAdjacentHTML('afterbegin', icon(navIcons[name]));
    tab.setAttribute('role','button'); tab.tabIndex = 0;
    tab.addEventListener('keydown', e => { if (e.key === 'Enter' || e.key === ' ') {e.preventDefault();e.stopPropagation();tab.click();} });
    nav.insertBefore(tab, nav.querySelector('.tab-spacer'));
  }
  // Retain the existing recursive tree, its double-click action, and filter identity.
  const tree = $('projectSidebar');
  $('workspaceProject').addEventListener('click', () => {
    const open = tree.classList.toggle('workspace-open');
    $('workspaceProject').setAttribute('aria-expanded', String(open));
    if (open) tree.querySelector('.active')?.scrollIntoView({block:'nearest'});
  });
  tree.addEventListener('click', () => state.refresh());
  document.addEventListener('click', e => {
    if (!tree.contains(e.target) && !$('workspaceProject').contains(e.target)) state.closeProjects();
  });
  document.addEventListener('keydown', e => {
    if (e.key === 'Escape') {state.closeProjects();document.body.classList.remove('workspace-mobile-chats');}
  });
  // Tree entries are regenerated by their established renderer.
  new MutationObserver(() => {
    for (const row of tree.querySelectorAll('.project-item')) {
      if (row.tabIndex !== 0) { row.tabIndex = 0; row.setAttribute('role','button'); }
    }
    state.refresh();
  }).observe(tree, {childList:true});
  tree.addEventListener('keydown', e => {
    if ((e.key === 'Enter' || e.key === ' ') && e.target.matches('.project-item')) {e.preventDefault();e.stopPropagation();e.target.click();}
  });
  $('workspaceCompleted').addEventListener('click', () => {
    if (_collapsedState.done) toggleDoneCollapsed();
    const header = document.querySelector('#sessionList .done-header');
    if (header) header.scrollIntoView({block:'start'});
    else showToast('No completed chats in this filter');
  });
  $('workspaceChatsToggle').addEventListener('click', () => {
    if (matchMedia('(max-width:760px)').matches) document.body.classList.toggle('workspace-mobile-chats');
    else document.body.classList.toggle('workspace-hide-chats');
    requestAnimationFrame(() => _fitVisibleWebTerms());
  });
  $('sessionList').addEventListener('dblclick', () => document.body.classList.remove('workspace-mobile-chats'));
  $('workspaceShortcuts').addEventListener('click', () => document.body.classList.toggle('workspace-shortcuts'));
  $('workspaceFork').addEventListener('click', async () => {
    if (!currentSessionId) return;
    const result = await showPrompt({title:'Fork with shared context',body:'Create a standalone chat from the linked conversation.',agentPicker:true,confirm:'Create fork',defaultAgent:'codex'});
    if (result) forkLinkedContext(currentSessionId, result.agent || 'codex');
  });
  $('workspaceFiles').addEventListener('click', () => inspector(false));
  $('workspaceChanges').addEventListener('click', () => {changesCwd='';inspector(true);});
  function inspector(changes) {
    changesVisible = changes;
    $('workspaceFiles').classList.toggle('active', !changes);
    $('workspaceChanges').classList.toggle('active', changes);
    $('filesTree').classList.toggle('hidden', changes);
    $('workspaceChangesList').classList.toggle('hidden', !changes);
    if (changes) loadChanges();
  }
  async function loadChanges() {
    const session = _findClientSession(currentSessionId);
    const cwd = session?.cwd || '';
    if (cwd === changesCwd) return;
    changesCwd = cwd; const generation = ++changesGeneration;
    const list = $('workspaceChangesList');
    $('workspaceChangesCount').textContent = '';
    list.textContent = cwd ? 'Reading working tree...' : 'Open a project chat to view changes';
    if (!cwd) return;
    try {
      const response = await fetch('/api/workspace-changes?cwd=' + encodeURIComponent(cwd), {signal:AbortSignal.timeout(10000)});
      const data = await response.json();
      if (generation !== changesGeneration) return;
      if (!response.ok || data.error) throw new Error(data.error || 'Could not read changes');
      list.replaceChildren();
      if (!data.is_git) {list.textContent='Not a Git repository';return;}
      const branch = document.createElement('p'); branch.textContent=data.branch || 'Detached HEAD';list.append(branch);
      $('workspaceChangesCount').textContent = data.changes.length || '';
      if (!data.changes.length) list.append(document.createTextNode('Working tree clean'));
      for (const file of data.changes) {
        const button = document.createElement('button');
        const status = document.createElement('b'); status.textContent=file.status;
        button.append(status, document.createTextNode(file.path));
        button.title = file.original_path ? `${file.original_path} -> ${file.path}` : file.path;
        button.addEventListener('click', () => openFileTab(data.root + '/' + file.path));
        list.append(button);
      }
      if (data.truncated) list.append(document.createTextNode('Showing first 500 changes'));
    } catch (error) {
      if (generation === changesGeneration) {list.textContent=error.message;changesCwd='';}
    }
  }
  function refresh() {
    const selected = _findClientSession(currentSessionId);
    const activeProject = tree.querySelector('.project-item.active');
    $('workspaceProjectName').textContent = currentProjectCwd
      ? (activeProject?.textContent.trim().replace(/^[\s▸▾]+/, '') || currentProjectCwd.split(/[\\/]/).filter(Boolean).pop())
      : 'All projects';
    $('workspaceProjectCount').textContent = `${projectChips.length} projects`;
    $('workspaceDoneCount').textContent = allSessions.filter(s => s.is_done).length || '';
    $('workspaceRuntimeCount').textContent = _activeTerms.size ? `${_activeTerms.size} open terminal${_activeTerms.size===1?'':'s'}` : 'No open terminals';
    $('workspaceBreadcrumb').textContent = selected?.cwd || selected?.project_short || '';
    $('convMeta').title = $('convMeta').textContent;
    $('workspaceContext').replaceChildren();
    if (selected) {
      const p = document.createElement('p'); p.textContent = selected.cwd || 'No project directory'; $('workspaceContext').append(p);
      const identity = document.createElement('p');identity.textContent = 'Session ' + currentSessionId.slice(0,8);identity.title=currentSessionId;$('workspaceContext').append(identity);
    }
    const members = currentSessionId ? _linkedGroupSids(currentSessionId) : [];
    if (state.singleSid && !members.includes(state.singleSid)) state.singleSid=null;
    const ids = members.length ? members : (currentSessionId ? [currentSessionId] : []);
    const signature = JSON.stringify([ids, state.singleSid, _gtkSplitActive, activeTermSid, convMode]);
    const agents = $('workspaceAgents');
    if (agents.dataset.signature !== signature) {
      agents.dataset.signature=signature;agents.replaceChildren();
      for (const sid of ids) {
        const agent = _agentOf(sid);
        const button = document.createElement('button');button.type='button';
        button.innerHTML = _agentBadge(agent) + esc(_agentLabel(agent));
        button.title = sid;button.setAttribute('aria-label', 'Show ' + _agentLabel(agent) + ' pane');
        button.classList.toggle('active', !_gtkSplitActive && sid === activeTermSid);
        button.addEventListener('click', () => {
          if (window.__nativeTerminalBridge) { openConv(sid); return; }
          state.singleSid=sid;switchCodeTab('__term__');_activateTermPane(sid);state.refresh();
        });
        agents.append(button);
      }
      if (ids.length>1 && !window.__nativeTerminalBridge) {
        const split=document.createElement('button');split.type='button';split.innerHTML=icon('columns-2')+'Split';split.classList.toggle('active',_gtkSplitActive);
        split.addEventListener('click',()=>{state.singleSid=null;switchCodeTab('__term__');_activateTermPane(currentSessionId);state.refresh();});agents.append(split);
      }
      icons();
    }
    document.querySelectorAll('.workspace-terminal-head').forEach(header => {
      const sid=header.parentElement.dataset.sid;const button=header.querySelector('button');
      if (button) {button.textContent=sid.slice(0,8);button.title='Copy session ID: '+sid;}
    });
    document.querySelectorAll('.tab').forEach(tab=>tab.setAttribute('aria-pressed',String(tab.classList.contains('active'))));
    document.querySelector('.settings-title').textContent=currentTab==='tooling'?'Tooling':'Persona';
    if (changesVisible) loadChanges();
  }
  // Observe identity/status only, never terminal output or the whole document.
  for (const id of ['convTitle','termStatus','termSessionIds']) new MutationObserver(state.refresh).observe($(id),{childList:true,characterData:true,subtree:true});
  setInterval(() => {
    if (changesVisible && currentTab === 'chats' && document.visibilityState === 'visible' && !$('filesPane').classList.contains('hidden')) {
      changesCwd='';loadChanges();
    }
  }, 10000);
  icons();state.refresh();
})();
